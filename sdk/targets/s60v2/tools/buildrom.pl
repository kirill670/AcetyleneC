      {
      print_source_error("Invalid Resource name: $ecomResourceName in ECOM_PLUGIN :$line");
      #treat as error if strict option selected;
      $errors++ if ($strict);
      }
      
    push @newobydata, "file=$emulatorDir\\$ecomFileName $fileRomDir\\$ecomFileName\n";
    push @newobydata, "data=MULTI_LINGUIFY(RSC $dataz_\\$resourceDir\\$ecomResourceName $resourceDir\\$ecomResourceName)\n";
      
      
    $line = reassert_sourceline();
    }
    elsif ($line =~ m/^.*__SCALABLE_IMAGE\(\s*(\S+)\s*,\s*(\S+)\s*,\s*(\S+)\s*,\s*(\S+)\s*\)/i)
     # __SCALABLE_IMAGE(emulator directory, file rom dir, dataz_, resource rom dir, filename, resource filename)
    {
    my $sourcepath="$1\\$2";
    my $targetpath=$3;
    my $filename=$4;
          

    #push @newobydata, "AUTO-BITMAP=test\\$sourcepath\\$filename.mbm $targetpath\\$filename.mbm\n";
    if( -e "$sourcepath\\$filename.mbm" )
      {
      push @newobydata, "AUTO-BITMAP=$sourcepath\\$filename.mbm $targetpath\\$filename.mbm\n";
      }
    if( -e "$sourcepath\\$filename.mif" )
      {
      push @newobydata, "data=$sourcepath\\$filename.mif $targetpath\\$filename.mif\n";
      }
    elsif( ! -e "$sourcepath\\$filename.mbm ")
      {
      print_source_error("Invalid Image name: $sourcepath\\$filename.mbm or .mif");
      #treat as error if strict option selected;
      $errors++ if ($strict);
      }      
    $line = reassert_sourceline();
    }
  push @newobydata, $line;
  }

@obydata = @newobydata;
