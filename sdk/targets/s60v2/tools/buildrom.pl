		{
		$romfiles{$2} .= "$1\n";
		next;
		}
	if ($line =~ /^\s*\S+(\[\S+\])\s*=\s*(\S+)\s+\\?(\S+)/)
		{
		$romfiles{$3} .= "$1$2\n";
		next;
		}
	if ($line =~ /^\s*\S+\s*=\s*(\S+)\s+\\?(\S+)/)
		{
		$romfiles{$2} .= "$1\n";
		next;
		}
	}

