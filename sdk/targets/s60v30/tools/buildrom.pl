sub fallback
	{
	my ($what,$file,$line) = @_;

	my $customizationFallback = CheckCustomization($file, $line);
 	return $customizationFallback if $customizationFallback;
 
	foreach my $toDIR (@binarySelectionOrder)
	{
		if( $file =~ /^(.*)\\$fromDIR\\(.*)$/)
		{
		my $newfile = "$1\\$toDIR\\$2";
		if (-e $newfile)
			{
			# Downgrade to the directory specified in order 
			print ">$file< not found in $fromDIR; Selecting from $toDIR\n" if ($warnSelection);
			$line =~ s/\\$fromDIR\\/\\$toDIR\\/;
			return $line;
			}
		}
	}
	
	# If the file is not found in GCCE, first select from ARMV5_ABIV2. If not present there also,
	# select from ARMV5 directory. This is necessary as some of the runtime DLLs will be present
	# only in ARMV5 directory. 
	if ($fromABI eq "" && $file =~ /^(.*)\\GCCE\\(.*)$/)
		{
			# Selecting from ARMV5_ABIV2 is a temporary phase during migration.
			# Will be removed once Symbian migrates to RVCT2.2 in ABIV2 mode.
			$fromDIR = "GCCE";
			my $toDIR = "ARMV5_ABIV2";
			my $newfile = "$1\\$toDIR\\$2";
			if (-e $newfile)
			{
				# Downgrade the selected ABI
				print ">$file not found in $fromDIR; Selecting from $toDIR\n" if ($warnSelection);
				$line =~ s/\\$fromDIR\\/\\$toDIR\\/;
				return $line;
			}
			else
			{
				my $toDIR = "ARMV5";
				my $newfile = "$1\\$toDIR\\$2";
				if (-e $newfile)
				{
					# Downgrade the selected ABI
					print ">$file not found in $fromDIR; Selecting from $toDIR\n" if ($warnSelection);
					$line =~ s/\\$fromDIR\\/\\$toDIR\\/;
					return $line;
				}
			}
		}

	# If file is not found in ARMV5_ABIV2, select from ARMV5. This is again a temporary phase until
	# ARMV5_ABIV2 is supported.
	if ($fromABI eq "" && $file =~ /^(.*)\\ARMV5_ABIV2\\(.*)$/)
	{
		$fromDIR = "ARMV5_ABIV2";
		my $toDIR = "ARMV5";
		my $newfile = "$1\\$toDIR\\$2";
		if (-e $newfile)
		{
