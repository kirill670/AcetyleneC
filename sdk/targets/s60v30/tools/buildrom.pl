			$line =~ s/\\$fromDIR\\/\\$toDIR\\/;
			return $line;
		}
	}
		
	if ($fromABI ne "" && $file =~ /^(.*)\\$fromABI\\(.*)$/)
		{
		my $newfile = "$1\\$toABI\\$2";
