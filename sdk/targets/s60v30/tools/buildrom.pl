sub match_obyfile
	{
	my ($obyfile) = @_;
	if (-f $obyfile)
		{
		push @obyfiles, $obyfile;
		return 1;
		}
	return 0;
	}

my $errors = 0;
foreach my $arg (@ARGV)
	{
	if ($arg =~ /^-[DI]/)
		{
		$cppargs .= " $arg";
		next;
		}
	if ($arg =~ /^-o(.*)/i)
		{
		$opt_o = $1;
		next;
		}
	if ($arg =~ /^-v$/)
		{
		$opt_v =1;
		next;
		}
	if ($arg =~ /^-s$/)
	{
	    $strict = 1;
	    next;
	}
	if ($arg =~ /^-w$/)
	{
	    $warnSelection = 1;
	    next;
	}
	
	if ($arg =~ /^-p$/)
	{
	    $preserve = 1;
	    next;
	}
	if ($arg =~ /^-nospi$/)
	{
			$createspi=0;
			$spiset=1;
			next;
	}
	if ($arg =~ /^-spi$/)
	{
			$createspi=1;
			$spiset=1;
			next;
	}	if ($arg =~ /^-/)
		{
		print "Unknown arg: $arg\n";
		$errors++;
		next;
		}
	# It's an OBY file
	#
	next if (match_obyfile($arg));
	next if (match_obyfile("$arg.oby"));
	next if (match_obyfile("$rominclude/$arg"));
	next if (match_obyfile("$rominclude/$arg.oby"));

	print "Cannot find oby file: $arg\n";
	$errors++;
	}

if (@obyfiles<1)
	{
	print "Missing obyfile argument\n";
	$errors++;
	}

if ($errors)
	{
	print_usage();
	exit 1;
	}

