sub run_rombuilder
	{
	my ($command, $obeyfile, $logfile) = @_;
	$command .= " $obeyfile.oby";
	print "* Executing $command\n" if ($opt_v);
	system($command);
	if ($? != 0)
		{
		$errors++;
		print "* ROMBUILD failed\n";
		}
	print "\n";
	rename "$logfile","$obeyfile.log" or die("* Can't rename $logfile\n");
	exit(1) if ($errors);
	}

